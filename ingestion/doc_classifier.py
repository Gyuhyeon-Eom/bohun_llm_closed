"""전사 텍스트 기반 서류 유형 분류 — 문서 유형 분류·자동매핑 기능 설계의 규칙(1차) 구현.

전량 스캔 덤프(파일명 무의미) 전제라 분류는 전사 '후' 텍스트로 수행한다.
분류가 틀려도 전사 원문은 전량 보존되므로 정보 손실이 없고(색인 제외·추출 대상
선정에만 영향), 재분류 한 번으로 복구된다. 저신뢰 건의 LLM 2차 분류는 검수 큐
후속 처리 몫 — 여기서는 파이프라인을 막지 않는 규칙 판정만 한다.
"""

# 유형 코드: 설계 문서 2장 분류 체계
DOC_TYPES = {
    "DEC": "심의·의결 서류", "MED-DX": "진단·소견", "MED-EX": "검사 결과",
    "MED-RC": "진료 기록", "SVC": "복무·인사 기록", "EVT": "경위·입증",
    "ADM": "신분·행정", "APP": "신청·민원", "ETC": "기타·미분류",
}

# (코드, 표제·본문 키워드) — 위에서부터 우선. 표제부 일치가 본문 일치보다 강한 신호.
_RULES = (
    ("DEC", ("심의의결서", "심의검토서", "의결 주문", "의결서")),
    ("MED-DX", ("장해진단서", "진단서", "소견서", "전문의 소견")),
    ("MED-EX", ("검사결과", "판독소견", "검사 결과지", "수술기록", "순음청력",
                "시야검사", "심초음파", "폐기능검사", "근전도", "방사선")),
    ("MED-RC", ("병상일지", "의무기록", "경과기록", "간호기록", "투약기록", "진료기록")),
    ("SVC", ("병적증명", "병적기록", "인사기록", "전역증", "복무확인", "거주표")),
    ("EVT", ("경위서", "인우보증", "진술서", "확인서", "목격")),
    ("ADM", ("주민등록", "가족관계증명", "위임장", "등본", "초본", "인감증명")),
    ("APP", ("등록신청서", "재판정 신청", "이의신청", "신청서")),
)


def classify(texts: list[str], head_pages: int = 2) -> tuple[str, str, str]:
    """(유형코드, 신뢰도, 근거 키워드).
    표제부(앞 페이지 상단) 일치 → 확정 / 본문 단일 유형 일치 → 보통 /
    무신호·복수 유형 → ETC 저신뢰(검수 큐 대상, 색인 제외하지 않음)."""
    head = "\n".join((t or "")[:600] for t in texts[:head_pages])
    body = "\n".join(t or "" for t in texts)[:8000]
    for code, kws in _RULES:
        for kw in kws:
            if kw in head:
                return code, "확정", kw
    hits = []
    for code, kws in _RULES:
        for kw in kws:
            if kw in body:
                hits.append((code, kw))
                break
    if len(hits) == 1:
        return hits[0][0], "보통", hits[0][1]
    return "ETC", "저신뢰", ""
